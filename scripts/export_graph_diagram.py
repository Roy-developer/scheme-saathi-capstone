"""Export the compiled journey graph as Mermaid (docs/GRAPH_DIAGRAM.md).

The diagram is drawn from the real compiled LangGraph, so it cannot drift
from the code. No client, model or network is used to compile it.

    python scripts/export_graph_diagram.py
"""

import sys
from pathlib import Path

from langgraph.checkpoint.memory import MemorySaver

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

NODE_NOTES = {
    "supervisor": "builds and shows the plan, routes each step, replans when a result contradicts it",
    "intake_agent": "asks only questions that can change a verdict; proposals need confirmation",
    "ask_user": "interrupt(): pauses for the person's answer (checkpointed, resumable)",
    "eligibility_agent": "observes the rule engine's verdict; never writes one",
    "scheme_search_tool": "hybrid search over scheme clauses",
    "document_agent": "read-only checklist and name/date comparison",
    "application_agent": "only node allowed to write drafts; submission needs exact approval",
}


def main() -> None:
    from src.workflow.journey import build_journey_graph

    graph = build_journey_graph(None, {}, checkpointer=MemorySaver())  # type: ignore[arg-type]
    mermaid = graph.get_graph().draw_mermaid()
    notes = "\n".join(f"- **{name}**: {text}" for name, text in NODE_NOTES.items())
    out = ROOT / "docs" / "GRAPH_DIAGRAM.md"
    out.write_text(
        "# Journey graph (LangGraph)\n\n"
        "Generated by `scripts/export_graph_diagram.py` from the compiled graph "
        "in `src/workflow/journey.py`. Do not edit by hand; rerun the script.\n\n"
        f"```mermaid\n{mermaid}\n```\n\n## Nodes\n\n{notes}\n\n"
        "## Where the minimum-bar items live\n\n"
        "- Typed state: `src/workflow/state.py`.\n"
        "- Conditional edges: out of `supervisor` (route to the next step) and "
        "`intake_agent` (ask again or continue).\n"
        "- Persistent checkpointer: SQLite via `AsyncSqliteSaver`; "
        "`scripts/demo_resume_after_kill.py` proves resume after a hard kill.\n"
        "- Human control: `ask_user` and the application approval gate use "
        "`interrupt()` / exact-payload approval.\n",
        encoding="utf-8",
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
